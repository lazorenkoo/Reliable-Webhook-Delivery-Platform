CREATE TABLE IF NOT EXISTS webhook_endpoints (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url VARCHAR(255),
    enabled BOOLEAN NOT NULL,
    signing_secret VARCHAR(255)
);

ALTER TABLE webhook_endpoints ADD COLUMN IF NOT EXISTS signing_secret VARCHAR(255);

CREATE TABLE IF NOT EXISTS endpoint_subscriptions (
    endpoint_id BIGINT NOT NULL REFERENCES webhook_endpoints(id),
    event_type VARCHAR(255) NOT NULL,
    PRIMARY KEY (endpoint_id, event_type)
);

CREATE TABLE IF NOT EXISTS events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(255),
    payload TEXT,
    created_at TIMESTAMP(6) WITH TIME ZONE,
    idempotency_key VARCHAR(255) UNIQUE
);

CREATE TABLE IF NOT EXISTS deliveries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT,
    endpoint_id BIGINT,
    http_status INTEGER,
    created_at TIMESTAMP(6) WITH TIME ZONE,
    completed_at TIMESTAMP(6) WITH TIME ZONE,
    attempt_count INTEGER,
    next_attempt_at TIMESTAMP(6) WITH TIME ZONE,
    processing_started_at TIMESTAMP(6) WITH TIME ZONE,
    processing_version BIGINT,
    manual_retry_processing BOOLEAN,
    last_error TEXT,
    status VARCHAR(255) CHECK (status IN ('PENDING', 'PROCESSING', 'SUCCEEDED', 'FAILED'))
);

CREATE TABLE IF NOT EXISTS delivery_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    delivery_id BIGINT,
    attempt_number INTEGER NOT NULL,
    http_status INTEGER,
    completed_at TIMESTAMP(6) WITH TIME ZONE,
    status VARCHAR(255) CHECK (status IN ('PENDING', 'PROCESSING', 'SUCCEEDED', 'FAILED')),
    error TEXT
);
