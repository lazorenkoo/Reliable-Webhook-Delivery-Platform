package com.lazorenkoo.relayforge.migration;

import java.sql.DriverManager;

import com.lazorenkoo.relayforge.endpoint.EndpointRepository;
import com.lazorenkoo.relayforge.endpoint.WebhookEndpoint;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;
import org.testcontainers.postgresql.PostgreSQLContainer;

import static org.junit.jupiter.api.Assertions.*;

@SpringBootTest(properties = {
        "spring.jpa.hibernate.ddl-auto=validate",
        "spring.flyway.baseline-on-migrate=true",
        "spring.flyway.baseline-version=0"
})
class LegacyMigrationIntegrationTest {

    private static final PostgreSQLContainer database = new PostgreSQLContainer("postgres:17.11");

    @Autowired
    private EndpointRepository endpoints;

    @Autowired
    private JdbcTemplate jdbc;

    @DynamicPropertySource
    static void configureDatabase(DynamicPropertyRegistry registry) throws Exception {
        database.start();
        try (var connection = DriverManager.getConnection(
                database.getJdbcUrl(), database.getUsername(), database.getPassword());
             var statement = connection.createStatement()) {
            statement.execute("CREATE TABLE webhook_endpoints ("
                    + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "enabled BOOLEAN NOT NULL, url VARCHAR(255) NOT NULL)");
            statement.execute("INSERT INTO webhook_endpoints (enabled, url) "
                    + "VALUES (false, 'https://example.com/old-webhook')");
        }
        registry.add("spring.datasource.url", database::getJdbcUrl);
        registry.add("spring.datasource.username", database::getUsername);
        registry.add("spring.datasource.password", database::getPassword);
        registry.add("spring.datasource.driver-class-name", () -> "org.postgresql.Driver");
    }

    @Test
    void migrationPreservesOldEndpointAndAllowsNewRecords() {
        WebhookEndpoint old = endpoints.findById(1L).orElseThrow();
        assertEquals("https://example.com/old-webhook", old.getUrl());
        assertFalse(old.isEnabled());
        assertNull(old.getSigningSecret());
        assertTrue(old.getSubscribedEvents().isEmpty());
        assertEquals(1, jdbc.queryForObject("SELECT count(*) FROM flyway_schema_history "
                + "WHERE version = '0' AND type = 'BASELINE' AND success", Integer.class));
        assertEquals(1, jdbc.queryForObject("SELECT count(*) FROM flyway_schema_history "
                + "WHERE version = '1' AND success", Integer.class));

        WebhookEndpoint next = new WebhookEndpoint();
        next.setUrl("https://example.com/new-webhook");
        next = endpoints.save(next);
        assertTrue(next.getId() > old.getId());
        assertEquals(2, endpoints.count());
        assertEquals(0, jdbc.queryForObject("SELECT count(*) FROM events", Integer.class));
        assertEquals(0, jdbc.queryForObject("SELECT count(*) FROM deliveries", Integer.class));
        assertEquals(0, jdbc.queryForObject("SELECT count(*) FROM delivery_attempts", Integer.class));
    }
}
